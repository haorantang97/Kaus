  vi.mocked(useProjectHistory).mockReturnValue({ items: [], projects, refresh: vi.fn() });
  vi.mocked(projectHistoryApi.choices).mockResolvedValue({ sources: [{ id: "codex", label: "Codex" }, { id: "claude-code", label: "Claude Code" }] });
