  vi.mocked(projectHistoryApi.add).mockResolvedValue({ archiveIds: ["h1"], count: 1 });
  vi.mocked(projectHistoryApi.list).mockResolvedValue({ items: [], projects });
  vi.mocked(projectHistoryApi.remove).mockResolvedValue({ removed: true });
